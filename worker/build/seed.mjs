/**
 * `npm run worker:seed:local` — the dev parity seed.
 *
 * PORT-CLOUDFLARE.md §5 says production starts empty and "the dev parity script
 * re-seeds test users". This is that script: it puts the same three accounts,
 * the same group passcode, the same two weekly rules and the same front-page
 * copy into the LOCAL D1 that `wrangler dev --local` reads, so the verification
 * matrix has something to verify against.
 *
 *   brian / writers2026   architect   (the board owner)
 *   dana  / brandnewpw1   member
 *   walt  / walter1234    member
 *   group passcode: remington2026
 *
 * Password hashes are computed HERE, in Node, with the identical WebCrypto
 * PBKDF2 parameters worker/src/auth/passwords.js uses — the module is imported
 * rather than reimplemented, so the iteration count can never drift between the
 * seed and the app. The result is written as a SQL file and applied with
 * `wrangler d1 execute --local`.
 *
 * IDEMPOTENT, with one deliberate exception. Rows that a leader might edit —
 * the weekly rules, the announcement, the about copy — are inserted only when
 * absent, so re-seeding never clobbers local edits. The three test ACCOUNTS are
 * upserted, password and role included, because a seed whose documented
 * credentials might not work is worse than useless. Nothing here is ever run
 * against a remote database: `--local` is hard-coded below.
 */

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

import { hashPassword, ITERATIONS } from '../src/auth/passwords.js';
import { mdToHtml } from '../src/util/sanitize.js';
import { ABOUT_DEFAULT_MD } from '../src/models.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const CONFIG = path.join(ROOT, 'worker', 'wrangler.toml');

/** SQL string literal. */
const q = (value) =>
  value === null || value === undefined ? 'NULL' : `'${String(value).replace(/'/g, "''")}'`;

const ACCOUNTS = [
  { username: 'brian', display_name: 'Brian', password: 'writers2026', role: 'architect' },
  { username: 'dana', display_name: 'Dana', password: 'brandnewpw1', role: 'member' },
  { username: 'walt', display_name: 'Walt', password: 'walter1234', role: 'member' },
];

const PASSCODE = 'remington2026';

/**
 * The group's actual rhythm, and the marker positions from the floor-map survey
 * (percentages of the 1000x600 viewBox — see views/partials/floormap.ejs):
 * Saturdays at the tables in front of the HILO stall on the left wall, Mondays
 * at the R. BAR island right of centre.
 */
const RULES = [
  {
    weekday: 6,
    time_hhmm: '13:00',
    title: 'Saturday sprints',
    location_label: 'The tables in front of Hilo',
    map_x: 15,
    map_y: 59.7,
    notes: null,
  },
  {
    weekday: 1,
    time_hhmm: '17:30',
    title: 'Monday sprints',
    location_label: 'By the r. bar',
    map_x: 63.4,
    map_y: 70,
    notes: null,
  },
];

const ANNOUNCEMENT = {
  title: 'The board is open',
  body_md: `This is where meeting times, the table we're sitting at and the drafts live.

Sign in with the group passcode any regular can tell you, then have a look at the
front page — the next session and the floor map are always at the top.`,
  is_pinned: 1,
};

async function main() {
  const lines = [];

  lines.push('-- Generated by worker/build/seed.mjs — local development only.');

  /* accounts */
  for (const a of ACCOUNTS) {
    const hash = await hashPassword(a.password);
    lines.push(
      `INSERT INTO users (username, display_name, password_hash, role, is_active)
       VALUES (${q(a.username)}, ${q(a.display_name)}, ${q(hash)}, ${q(a.role)}, 1)
       ON CONFLICT(username) DO UPDATE SET
         display_name  = excluded.display_name,
         password_hash = excluded.password_hash,
         role          = excluded.role,
         role_expires_at = NULL,
         is_active     = 1;`
    );
  }

  /* group passcode + site name */
  const passcodeHash = await hashPassword(PASSCODE);
  lines.push(
    `INSERT INTO settings (key, value, updated_at)
     VALUES ('group_passcode_hash', ${q(passcodeHash)}, datetime('now'))
     ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at;`
  );
  lines.push(
    `INSERT INTO settings (key, value, updated_at)
     VALUES ('site_name', 'AFWC Board', datetime('now'))
     ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at;`
  );

  /* about copy — only when missing, so a leader's edit survives a re-seed */
  lines.push(
    `INSERT INTO settings (key, value, updated_at)
     VALUES ('about_md', ${q(ABOUT_DEFAULT_MD)}, datetime('now'))
     ON CONFLICT(key) DO NOTHING;`
  );

  /* weekly rules — matched on (weekday, time_hhmm, title) */
  for (const r of RULES) {
    lines.push(
      `INSERT INTO recurring_meetings
         (weekday, time_hhmm, title, location_label, map_x, map_y, notes, is_active, created_by)
       SELECT ${r.weekday}, ${q(r.time_hhmm)}, ${q(r.title)}, ${q(r.location_label)},
              ${r.map_x}, ${r.map_y}, ${q(r.notes)}, 1,
              (SELECT id FROM users WHERE username = 'brian')
        WHERE NOT EXISTS (
          SELECT 1 FROM recurring_meetings
           WHERE weekday = ${r.weekday} AND time_hhmm = ${q(r.time_hhmm)} AND title = ${q(r.title)}
        );`
    );
  }

  /* one announcement — matched on title */
  const body_html = mdToHtml(ANNOUNCEMENT.body_md);
  lines.push(
    `INSERT INTO announcements (title, body_html, body_md, is_pinned, author_id)
     SELECT ${q(ANNOUNCEMENT.title)}, ${q(body_html)}, ${q(ANNOUNCEMENT.body_md)},
            ${ANNOUNCEMENT.is_pinned}, (SELECT id FROM users WHERE username = 'brian')
      WHERE NOT EXISTS (
        SELECT 1 FROM announcements WHERE title = ${q(ANNOUNCEMENT.title)} AND deleted_at IS NULL
      );`
  );

  const sqlFile = path.join(os.tmpdir(), `afwc-seed-${process.pid}.sql`);
  fs.writeFileSync(sqlFile, lines.join('\n\n'), 'utf8');

  try {
    execFileSync(
      'npx',
      ['wrangler', 'd1', 'execute', 'DB', '--local', '--config', CONFIG, '--file', sqlFile],
      { stdio: 'inherit', cwd: ROOT }
    );
  } finally {
    fs.unlinkSync(sqlFile);
  }

  console.log(`\n[seed] done (PBKDF2 ${ITERATIONS} iterations)`);
  console.log('[seed] brian / writers2026  (architect)');
  console.log('[seed] dana  / brandnewpw1  (member)');
  console.log('[seed] walt  / walter1234   (member)');
  console.log(`[seed] group passcode: ${PASSCODE}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
